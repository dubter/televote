#!/usr/bin/env bash
# Перезапуск консьюмера под нагрузкой.
#
# Kafka доставляет at-least-once: ребаланс группы переигрывает сообщения.
# Проверяем, что дубли доставки НЕ завысили результат — на этом держится
# идемпотентность применения голоса.
set -euo pipefail
cd "$(dirname "$0")/../.."
source scripts/chaos/lib.sh

printf '\n  chaos: перезапуск консьюмера и ребаланс группы\n\n'

TOKEN=$(admin_token); [ -n "$TOKEN" ] || fail "не удалось войти в админку"
SLUG="chaos-consumer-$$"
create_poll "$SLUG" "$TOKEN"
say "опрос создан"

sent=$(cast_votes "$SLUG" 1 100)
say "принято: ${sent}"

# Убиваем инстанс сразу после приёма: часть сообщений ещё не применена,
# оффсеты не закоммичены, и после возврата они придут повторно.
$COMPOSE restart -t 0 app-1 >/dev/null 2>&1
say "app-1 перезапущен — группа ребалансится, часть сообщений придёт повторно"
sleep 12

got=$(await_drain "$SLUG" "$TOKEN" "$sent")
[ "$got" = "$sent" ] || fail "посчитано ${got} вместо ${sent} — ребаланс исказил счёт"

printf '\n  Пройден: %s принято, %s посчитано — повторная доставка не удвоила счёт.\n\n' "$sent" "$got"
